def _dummy_node_utilization() -> tuple[np.ndarray, np.ndarray]:
    """Return node-wise utilization and role aggregate placeholder values.

    The fs-native backend is local to the replay host, so its six storage-node
    cells are N/A and only its aggregate replay-host value is populated.
    """

    workload_factor = np.array([0.78, 0.94, 1.08, 1.0, 0.86])
    disk_base = {"fs-native": 82.0, "3FS": 61.0, "pNFS": 72.0}
    network_base = {"fs-native": 12.0, "3FS": 74.0, "pNFS": 66.0}
    disk_values = np.full((len(WORKLOADS), len(BACKENDS), 6), np.nan)
    network_values = np.full_like(disk_values, np.nan)

    disk_skew = {
        "3FS": np.array([0.90, 0.96, 1.02, 1.04, 0.98, 1.12]),
        "pNFS": np.array([0.82, 0.95, 1.03, 1.08, 0.94, 1.34]),
    }
    network_skew = {
        "3FS": np.array([0.90, 1.02, 1.08, 0.96, 1.12, 1.24]),
        "pNFS": np.array([0.94, 0.98, 1.04, 1.10, 0.92, 1.18]),
    }

    for workload_index, workload in enumerate(WORKLOADS):
        for backend_index, backend in enumerate(BACKENDS):
            if backend == "fs-native":
                continue
            disk_values[workload_index, backend_index] = np.clip(
                disk_base[backend]
                * workload_factor[workload_index]
                * disk_skew[backend],
                0,
                98,
            )
            network_values[workload_index, backend_index] = np.clip(
                network_base[backend]
                * (0.86 + 0.18 * workload_factor[workload_index])
                * network_skew[backend],
                0,
                98,
            )

    aggregate_shape = (len(WORKLOADS), len(BACKENDS), 1)
    disk_aggregate = np.full(aggregate_shape, np.nan)
    network_aggregate = np.full(aggregate_shape, np.nan)
    disk_aggregate[:, 0, 0] = np.clip(disk_base["fs-native"] * workload_factor, 0, 98)
    network_aggregate[:, 0, 0] = np.clip(
        network_base["fs-native"] * (0.86 + 0.18 * workload_factor), 0, 98
    )
    disk_aggregate[:, 1:, 0] = np.mean(disk_values[:, 1:, :], axis=2)
    network_aggregate[:, 1:, 0] = np.mean(network_values[:, 1:, :], axis=2)
    return (
        np.concatenate((disk_values, disk_aggregate), axis=2),
        np.concatenate((network_values, network_aggregate), axis=2),
    )


def _dummy_utilization() -> tuple[np.ndarray, np.ndarray]:
    workload_factor = np.array([0.78, 0.94, 1.08, 1.0, 0.86])
    disk_base = {"fs-native": 82.0, "3FS": 61.0, "pNFS": 72.0}
    network_base = {"fs-native": 12.0, "3FS": 74.0, "pNFS": 66.0}
    disk = np.column_stack(
        [np.clip(disk_base[backend] * workload_factor, 0, 98) for backend in BACKENDS]
    )
    network = np.column_stack(
        [
            np.clip(network_base[backend] * (0.86 + 0.18 * workload_factor), 0, 98)
            for backend in BACKENDS
        ]
    )
    return disk, network


