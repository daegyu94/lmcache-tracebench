def _seed(*labels: str) -> int:
    return sum(
        (index + 1) * ord(char) for index, text in enumerate(labels) for char in text
    )


def _dummy_throughput(
    workload: str, backend: str, elapsed_seconds: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Return deterministic, bursty read/write GB/s time series."""

    normalized = elapsed_seconds / elapsed_seconds.max()
    phase = (_seed(workload) % 23) / 11.0
    base = WORKLOAD_BASE[workload] * BACKEND_FACTOR[backend]
    burst_center = 0.28 + 0.08 * (list(WORKLOADS).index(workload) % 3)
    burst = np.exp(-(((normalized - burst_center) / 0.12) ** 2))
    tail = np.exp(-(((normalized - 0.76) / 0.16) ** 2))
    rng = np.random.default_rng(_seed(workload, backend))

    read = base * (
        0.54
        + 0.21 * np.sin(4.2 * np.pi * normalized + phase)
        + 0.40 * burst
        + 0.16 * tail
    )
    write = base * (
        0.38
        + 0.17 * np.cos(3.4 * np.pi * normalized + phase / 2)
        + 0.24 * burst
        + 0.29 * tail
    )
    read += rng.normal(0.0, 0.035 * base, elapsed_seconds.size)
    write += rng.normal(0.0, 0.030 * base, elapsed_seconds.size)
    return np.clip(read, 0.03, None), np.clip(write, 0.03, None)


def _add_dummy_watermark(fig: plt.Figure) -> None:
    fig.text(
        0.995,
        0.006,
        "DUMMY DATA — NOT MEASURED",
        ha="right",
        va="bottom",
        fontsize=8,
        weight="bold",
        color="#555555",
        bbox={
            "boxstyle": "round,pad=0.25",
            "facecolor": "#FFF3CD",
            "edgecolor": "#D6B656",
            "linewidth": 0.7,
        },
    )


def _assert_layout_clear(fig: plt.Figure) -> None:
    """Reject figure-level text/legend overlap and canvas clipping."""

    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    canvas = fig.bbox
    graph_boxes = [axis.get_window_extent(renderer) for axis in fig.axes]
    figure_artists = [
        artist for artist in (*fig.texts, *fig.legends) if artist.get_visible()
    ]

    for artist in figure_artists:
        bbox = artist.get_window_extent(renderer)
        get_text = getattr(artist, "get_text", None)
        label = get_text() if get_text is not None else artist.__class__.__name__
        if any(bbox.overlaps(graph_box) for graph_box in graph_boxes):
            raise RuntimeError(f"Figure-level artist overlaps a graph box: {label!r}")
        if (
            bbox.x0 < canvas.x0 - 1
            or bbox.y0 < canvas.y0 - 1
            or bbox.x1 > canvas.x1 + 1
            or bbox.y1 > canvas.y1 + 1
        ):
            raise RuntimeError(
                f"Figure-level artist is clipped by the canvas: {label!r}"
            )

    for axis in fig.axes:
        bbox = axis.get_tightbbox(renderer)
        if bbox is None:
            continue
        if (
            bbox.x0 < canvas.x0 - 1
            or bbox.y0 < canvas.y0 - 1
            or bbox.x1 > canvas.x1 + 1
            or bbox.y1 > canvas.y1 + 1
        ):
            raise RuntimeError("Axis decoration is clipped by the canvas")


def _save(fig: plt.Figure, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    _assert_layout_clear(fig)
    fig.savefig(destination, facecolor="white")
    plt.close(fig)


def plot_throughput_family(
    family: str, workloads: tuple[str, ...], output_dir: Path
) -> None:
    elapsed_seconds = np.arange(0.0, 125.0, 5.0)
    fig, axes = plt.subplots(
        len(workloads),
        len(BACKENDS),
        figsize=(13.6, 3.0 * len(workloads)),
        sharex=True,
        sharey=True,
        squeeze=False,
    )
    maximum_throughput = 0.0

    for row, workload in enumerate(workloads):
        for column, backend in enumerate(BACKENDS):
            axis = axes[row, column]
            read, write = _dummy_throughput(workload, backend, elapsed_seconds)
            maximum_throughput = max(
                maximum_throughput, float(read.max()), float(write.max())
            )
            axis.plot(elapsed_seconds, read, color=READ_COLOR, label="L2 read")
            axis.plot(
                elapsed_seconds,
                write,
                color=WRITE_COLOR,
                linestyle="--",
                label="L2 write",
            )
            if row == 0:
                axis.set_title(backend)
            axis.set_xlim(elapsed_seconds.min(), elapsed_seconds.max())

    axes[0, 0].set_ylim(0, maximum_throughput * 1.08)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.965),
        ncols=2,
        frameon=False,
    )
    fig.suptitle(
        f"Time-varying L2 throughput — {family.title()}",
        fontsize=15,
        weight="bold",
        y=0.995,
    )
    fig.text(
        0.020,
        0.48,
        "Throughput [GB/s]",
        rotation=90,
        va="center",
        ha="center",
        fontsize=10,
    )
    fig.supxlabel("Elapsed time [s]", y=0.035, fontsize=10)
    for row, workload in enumerate(workloads):
        axes[row, -1].yaxis.set_label_position("right")
        axes[row, -1].set_ylabel(
            workload,
            rotation=270,
            labelpad=20,
            va="center",
            weight="bold",
        )
    _add_dummy_watermark(fig)
    fig.tight_layout(rect=(0.045, 0.065, 0.98, 0.90), h_pad=1.2, w_pad=1.0)
    _save(fig, output_dir / f"l2-throughput-{family}.png")


def _dummy_speedup_metrics(
    workload: str, backend: str
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    workload_scale = WORKLOAD_BASE[workload]
    backend_scale = BACKEND_FACTOR[backend]
    capacity = (
        workload_scale
        * backend_scale
        * {
            "fs-native": 1.85,
            "3FS": 2.55,
            "pNFS": 2.20,
        }[backend]
    )
    offered = workload_scale * 0.78 * SPEEDUPS
    wall_throughput = capacity * (1.0 - np.exp(-offered / capacity))

    knee = {"fs-native": 1.4, "3FS": 2.2, "pNFS": 1.8}[backend]
    overload = np.maximum(SPEEDUPS / knee - 1.0, 0.0)
    read_p99_ms = (2.8 / backend_scale) * (1.0 + 0.13 * SPEEDUPS + 3.1 * overload**2)
    max_schedule_lag_s = 0.015 * SPEEDUPS + 1.9 * overload**2
    return wall_throughput, read_p99_ms, max_schedule_lag_s


def plot_speedup_impact(output_dir: Path) -> None:
    metric_rows = (
        ("Wall throughput [GB/s]", 0),
        ("Read p99 latency [ms]", 1),
        ("Max schedule lag [s]", 2),
    )
    fig, axes = plt.subplots(
        len(metric_rows),
        len(WORKLOADS),
        figsize=(15.8, 9.0),
        sharex=True,
        squeeze=False,
    )

    for column, workload in enumerate(WORKLOADS):
        for backend in BACKENDS:
            metrics = _dummy_speedup_metrics(workload, backend)
            for row, (_, metric_index) in enumerate(metric_rows):
                axis = axes[row, column]
                values = metrics[metric_index]
                spread = values * (0.04 + 0.01 * row)
                axis.plot(
                    SPEEDUPS,
                    values,
                    color=BACKEND_COLORS[backend],
                    marker="o",
                    markersize=3.8,
                    label=backend,
                )
                axis.fill_between(
                    SPEEDUPS,
                    np.maximum(values - spread, 0),
                    values + spread,
                    color=BACKEND_COLORS[backend],
                    alpha=0.10,
                    linewidth=0,
                )

        axes[0, column].set_title(workload)
        axes[-1, column].set_xlabel("Replay speedup [x]")
        for row, (ylabel, _) in enumerate(metric_rows):
            axes[row, column].set_xscale("log", base=2)
            axes[row, column].set_xticks(
                SPEEDUPS, labels=tuple(f"{speedup:g}" for speedup in SPEEDUPS)
            )
            axes[row, column].set_ylim(bottom=0)
            if column == 0:
                axes[row, column].set_ylabel(ylabel)

    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.965),
        ncols=3,
        frameon=False,
    )
    fig.suptitle(
        "Replay speedup impact by workload and backend",
        fontsize=15,
        weight="bold",
        y=0.995,
    )
    _add_dummy_watermark(fig)
    fig.tight_layout(rect=(0, 0, 1, 0.91))
    _save(fig, output_dir / "replay-speedup-impact.png")


def _dummy_latency_diagnostics(
    workload: str, backend: str, speedup: float = REFERENCE_SPEEDUP
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return task latency percentiles and non-additive replay delay metrics."""

    percentile_shape = np.array([1.0, 1.75, 4.0])
    workload_scale = 0.82 + 0.32 * WORKLOAD_BASE[workload]
    backend_scale = {"fs-native": 1.35, "3FS": 0.78, "pNFS": 1.0}[backend]
    overload = max(
        speedup / {"fs-native": 1.4, "3FS": 2.2, "pNFS": 1.8}[backend] - 1.0, 0.0
    )
    queue_amplification = 1.0 + 1.8 * overload**2
    read_ms = (
        2.2 * workload_scale * backend_scale * percentile_shape * queue_amplification
    )
    write_ms = (
        1.8
        * workload_scale
        * backend_scale
        * percentile_shape
        * (1.0 + 1.3 * overload**2)
    )

    dependency_ms = 12.0 * workload_scale * (1.0 + 22.0 * overload**2)
    buffer_ms = 8.0 * backend_scale * (1.0 + 16.0 * overload**2)
    schedule_ms = dependency_ms + buffer_ms + 4.0 * (1.0 + overload)
    replay_delays_ms = np.array([dependency_ms, buffer_ms, schedule_ms])
    return read_ms, write_ms, replay_delays_ms


