"""Render placeholder figures for the LMCache L2 performance report.

All values generated by this script are synthetic.  The plots intentionally
carry a visible DUMMY DATA watermark so they cannot be confused with measured
benchmark results.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

WORKLOAD_GROUPS = {
    "tensormesh": ("GAIA", "WildClaw", "SWE-bench"),
    "mooncake": ("ToolAgent", "Conversation"),
}
WORKLOADS = WORKLOAD_GROUPS["tensormesh"] + WORKLOAD_GROUPS["mooncake"]
REPRESENTATIVE_WORKLOADS = ("SWE-bench", "Conversation")
BACKENDS = ("fs-native", "3FS", "pNFS")
SPEEDUPS = np.array([1.0, 1.25, 1.5, 2.0])
REFERENCE_SPEEDUP = float(SPEEDUPS[-1])

BACKEND_COLORS = {
    "fs-native": "#0072B2",
    "3FS": "#D55E00",
    "pNFS": "#009E73",
}
READ_COLOR = "#0072B2"
WRITE_COLOR = "#E69F00"

WORKLOAD_BASE = {
    "GAIA": 0.72,
    "WildClaw": 0.98,
    "SWE-bench": 1.24,
    "ToolAgent": 1.08,
    "Conversation": 0.82,
}
BACKEND_FACTOR = {"fs-native": 0.82, "3FS": 1.18, "pNFS": 1.0}


