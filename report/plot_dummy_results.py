def plot_nodewise_resource_utilization(output_dir: Path) -> None:
    disk, network = _dummy_node_utilization()
    node_labels = tuple(f"storage-{index}" for index in range(1, 7)) + ("aggregate",)
    swebench_index = WORKLOADS.index("SWE-bench")
    speedups = (1.0, 2.0)
    speedup_factors = {
        "disk": {
            1.0: {"fs-native": 1.00, "3FS": 1.00, "pNFS": 1.00},
            2.0: {"fs-native": 1.12, "3FS": 1.05, "pNFS": 1.09},
        },
        "network": {
            1.0: {"fs-native": 1.00, "3FS": 1.00, "pNFS": 1.00},
            2.0: {"fs-native": 1.04, "3FS": 1.10, "pNFS": 1.08},
        },
    }
    resource_specs = (
        (disk, "Storage device utilization (p95)", "disk"),
        (network, "Network directional utilization (p95)", "network"),
    )
    fig, axes = plt.subplots(
        2,
        2,
        figsize=(11.2, 8.0),
        sharey=True,
        layout="constrained",
    )
    image = None
    cmap = plt.get_cmap("YlOrRd").copy()
    cmap.set_bad("#E5E7EB")

    for row, speedup in enumerate(speedups):
        for column, (values, title, resource) in enumerate(resource_specs):
            axis = axes[row, column]
            base_nodes = values[swebench_index, :, :6]
            factors = np.array(
                [speedup_factors[resource][speedup][backend] for backend in BACKENDS]
            )
            nodes = np.clip(base_nodes * factors[:, None], 0, 98)
            aggregate = np.clip(values[swebench_index, :, -1] * factors, 0, 98)
            matrix = np.vstack((nodes.T, aggregate))
            image = axis.imshow(matrix, aspect="auto", cmap=cmap, vmin=0, vmax=100)
            axis.set_title(f"{title}\nSWE-bench · replay speedup x{speedup:g}")
            axis.set_xticks(np.arange(len(BACKENDS)), BACKENDS)
            axis.set_yticks(np.arange(len(node_labels)), node_labels)
            axis.set_xlabel("L2 backend")
            axis.axhline(len(node_labels) - 1.5, color="#222222", linewidth=1.2)
            for cell_row in range(matrix.shape[0]):
                for cell_column in range(matrix.shape[1]):
                    value = matrix[cell_row, cell_column]
                    if np.isnan(value):
                        cell_label = "N/A"
                        text_color = "#555555"
                    else:
                        cell_label = f"{value:.0f}"
                        text_color = "white" if value >= 62 else "#222222"
                    axis.text(
                        cell_column,
                        cell_row,
                        cell_label,
                        ha="center",
                        va="center",
                        fontsize=9,
                        color=text_color,
                    )
            if column == 0:
                axis.set_ylabel("Storage node / aggregate")

    assert image is not None
    fig.colorbar(
        image,
        ax=axes.ravel().tolist(),
        label="p95 utilization [%]",
        shrink=0.86,
    )
    fig.suptitle(
        "SWE-bench node-wise and aggregate resource utilization: x1 vs. x2",
        fontsize=15,
        weight="bold",
    )
    _add_dummy_watermark(fig)
    _save(fig, output_dir / "resource-utilization-nodewise.png")


def _dummy_storage_node_scaling() -> tuple[
    np.ndarray, dict[str, dict[str, np.ndarray]]
]:
    """Return synthetic SWE-bench scaling curves for one through six nodes."""

    node_counts = np.arange(1.0, 7.0)
    metrics: dict[str, dict[str, np.ndarray]] = {}

    metrics["fs-native"] = {
        # fs-native is a local reference and is not scaled by storage-node count.
        "throughput": np.full_like(node_counts, 1.55),
        "latency": np.full_like(node_counts, 10.5),
        "storage": np.full_like(node_counts, 71.0),
        "network": np.full_like(node_counts, np.nan),
    }
    metrics["3FS"] = {
        "throughput": 5.0 * (1.0 - np.exp(-node_counts / 2.8)),
        "latency": 6.5 + 25.0 * np.exp(-node_counts / 2.0),
        "storage": np.clip(88.0 / np.sqrt(node_counts) + 4.0, 0, 98),
        "network": np.clip(35.0 + 65.0 * (1.0 - np.exp(-node_counts / 2.0)), 0, 98),
    }
    metrics["pNFS"] = {
        "throughput": 4.5 * (1.0 - np.exp(-node_counts / 3.1)),
        "latency": 7.2 + 23.0 * np.exp(-node_counts / 2.2),
        "storage": np.clip(82.0 / np.sqrt(node_counts) + 6.0, 0, 98),
        "network": np.clip(29.0 + 63.0 * (1.0 - np.exp(-node_counts / 2.3)), 0, 98),
    }
    return node_counts, metrics


def plot_storage_node_scaling(output_dir: Path) -> None:
    node_counts, metrics = _dummy_storage_node_scaling()
    metric_specs = (
        ("throughput", "Aggregate L2 throughput", "GB/s"),
        ("latency", "Read p99 latency", "ms"),
        ("storage", "Storage device utilization (p95)", "%"),
        ("network", "Network directional utilization (p95)", "%"),
    )
    fig, axes = plt.subplots(
        2,
        2,
        figsize=(11.4, 8.0),
        sharex=True,
        squeeze=False,
    )

